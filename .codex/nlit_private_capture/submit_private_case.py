"""Run ONE NEW local NLIT request through the normal LOCAL_TEST sender.

No browser, supervisor or fixture is generated by this helper. Execute only
after a dedicated supervisor and private authenticated browser are verified.
The original case text is read from an ACL-private local file, never argv or Git.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import re


def main() -> int:
    cli = argparse.ArgumentParser()
    cli.add_argument("--test-workspace", type=Path, required=True)
    cli.add_argument("--private-root", type=Path, required=True)
    cli.add_argument("--case-file", type=Path, required=True)
    cli.add_argument("--case-id", required=True)
    cli.add_argument("--timeout", type=float, default=900.0)
    args = cli.parse_args()
    token = os.environ.get("SMARTAGENT_NLIT_CAPTURE_NONCE", "")
    if not re.fullmatch(r"[0-9a-fA-F]{32,128}", token):
        raise SystemExit("NEW_OPT_IN_NONCE_REQUIRED")
    if (os.environ.get("SMARTAGENT_NLIT_CAPTURE_ENABLED") != "1"
            or os.environ.get("SMARTAGENT_NLIT_PRIVATE_ACL_CONFIRMED") != "YES"):
        raise SystemExit("PRIVATE_OPT_IN_NOT_CONFIRMED")
    if not re.fullmatch(r"NLIT-NEW-[A-Za-z0-9_-]{10,80}", args.case_id):
        raise SystemExit("ONLY_NEW_CASE_IDS_ALLOWED")
    private = args.private_root.resolve(strict=True)
    source = args.case_file.resolve(strict=True)
    if source == private or private not in source.parents:
        raise SystemExit("CASE_FILE_MUST_STAY_IN_PRIVATE_ROOT")
    if not args.test_workspace.resolve(strict=True).is_dir():
        raise SystemExit("TEST_WORKSPACE_NOT_FOUND")
    case = source.read_text(encoding="utf-8")
    if not case.strip() or len(case.encode("utf-8")) > 16000:
        raise SystemExit("INVALID_PRIVATE_CASE_SIZE")
    from RemoteAgent.local_telegram_sender import send_and_wait
    request = ("NLIT_TRACE_TOKEN=" + token + "\n"
               + "NLIT_NEW_CASE_ID=" + args.case_id + "\n" + case)
    return send_and_wait(
        request=request, workspace=str(args.test_workspace.resolve()),
        timeout_sec=args.timeout,
    )


if __name__ == "__main__":
    raise SystemExit(main())
